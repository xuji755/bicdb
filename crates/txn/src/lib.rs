//! # bicdb-txn
//!
//! 事务状态机、语句快照、行锁、Undo、死锁检测
//!
//! - 设计依据：§8 崩溃恢复契约（§4.6.6 事务生命周期、§11.1.1 提交流程）
//! - 对应阶段：**P3**（已启动；本片 = `写路径`——**DML 经缓冲池落地**）
//! - 当前状态：**v0.6**——[`engine`]（**事务引擎门面**，REQ-ENG-002：
//!   `begin`/`snapshot`/`commit`/`rollback`/`语句回滚点`/`lock_row`，**句柄不透明**；
//!   `lock_row` 纯加锁落行级痕）、[`write`]（写路径：`Txn` 生命周期 + `insert`/`commit`/
//!   `rollback` 经缓冲池；undo 页**受 redo 保护**；提交 = 提交记录刷盘后返回）；
//!   **语句回滚点与等待-重试驱动**（P4）：`statement_mark`/`rollback_to_mark`
//!   （§4.6.6 ②：不释锁、不回滚此前语句；链头置回回滚点 ⇒ 孤链不可达）、
//!   `execute_with_wait`（§5.4.2：登记 → 挂起 → 醒来重试；死锁环上修改量
//!   最少者**语句级回滚**后返回 `DeadlockVictim`）；[`lock::WaitGate`]
//!   （登记/挂起/唤醒同一把内部锁——**唤醒不丢**：标记兜底"唤醒先于挂起"）。
//!   `delete`/`update`（更新类撤销）已落；撤销段自动扩展**经池 + redo**
//!   （`ensure_undo_capacity`）。
//!   （v0.4，P4 行迁移切片）**改长更新 ⇒ 行迁移**（§6.2）：不增就地重写、
//!   增长迁移（同页优先、跨页经分配口），原槽位 6B 转发指针、ROWID 不变；
//!   记录 = 删除旧位置 + 插入新位置（§12.4）；`UpdateTooLong` 明确拒绝
//!   超过单页的新行（转链路径随后续切片）。
//!   （v0.3，P3 审核修复）**ITL 占用收口**：`occupy_itl` = 延迟块清除 →
//!   每事务每块至多一个条目 → 新占用必记带 `txn_id` 的 `ITL 覆盖`（归属守卫
//!   防幽灵记录）→ 行头 `itl_slot` 回填；insert 预检先行（失败不留链上记录）；
//!   提交点 = 提交记录耐久（槽标记失败不回滚，由恢复前滚补标记兜底）；
//!   **新撤销页先 fsync 落盘、后进 redo**（物理增量无法重建不存在的页）。
//!
//! 配套：[`snapshot`]（最老快照集合，§12.7——undo 回收的唯一输入）、
//! [`lock`]（行锁的等待结构与死锁检测，§5.4.2）、[`index_io`]
//! （**带 redo 的索引写口**——`bicdb_index::IndexIo` 的生产实现：段空间分配
//! 走计划形态 + 经池 + redo，全新页先格式化落盘 + fsync，`page_lsn` 前置）。
//!
//! 三条纪律（§11.1）：
//! 1. **写先入缓存**——DML 只改缓冲池里的页，脏页由 DBWR（Make Free/检查点）写回；
//! 2. **先 undo 后变更**——每次修改先落撤销记录（含其 redo），再改数据页；
//! 3. **提交 = 提交记录耐久**——提交记录刷盘成功才向客户端返回（§11.5.5）。

